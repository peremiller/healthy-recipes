export function recipeVisualNameKey(value) {
  return String(value || "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "")
    .toLowerCase().replace(/[^a-z0-9]+/g, " ").trim();
}

// Quantities are not visual portion guides. Any added, removed or renamed food
// invalidates the reviewed illustration; changing a quantity does not assert that
// a generated portion is a measured serving.
function recipeVisualIngredientSignature(recipe) {
  return (Array.isArray(recipe?.ingredients) ? recipe.ingredients : [])
    .map((ingredient) => recipeVisualNameKey(ingredient?.name)).sort().join("|");
}

export function recipeVisualMethodSignature(recipe) {
  const method = (Array.isArray(recipe?.steps) ? recipe.steps : []).map(recipeVisualNameKey).join("|");
  let hash = 2166136261;
  for (let index = 0; index < method.length; index += 1) hash = Math.imul(hash ^ method.charCodeAt(index), 16777619) >>> 0;
  return hash.toString(16).padStart(8, "0");
}

export function recipeVisualSignature(recipe) {
  return `${recipeVisualIngredientSignature(recipe)}||method:${recipeVisualMethodSignature(recipe)}`;
}

const byName = new Map();
const reviewedMethods = new Map(REVIEWED_VISUAL_METHOD_VARIANTS.map((variant) =>
  [recipeVisualNameKey(variant.name), recipeVisualMethodSignature(variant)]));
for (const entry of RECIPE_VISUAL_MANIFEST) {
  for (const name of [entry.name, ...entry.aliases]) {
    const key = recipeVisualNameKey(name);
    const matches = byName.get(key) || [];
    if (!matches.includes(entry)) matches.push(entry);
    byName.set(key, matches);
  }
}

export function resolveRecipeVisual(recipe) {
  const signature = recipeVisualSignature(recipe);
  if (recipe?.visualMode === "custom" && recipe?.image) {
    let safeUrl = false;
    try {
      const parsed = new URL(recipe.image);
      safeUrl = parsed.protocol === "https:" && !parsed.username && !parsed.password;
    } catch { /* Untrusted custom input is never an image fallback. */ }
    const verified = safeUrl && recipe.photoConfirmed === true &&
      recipe.photoReview?.confirmed === true &&
      recipe.photoReview.url === recipe.image &&
      recipe.photoReview.ingredientSignature === signature &&
      recipe.photoReview.name === recipe.name;
    return verified
      ? { status: "user-confirmed", kind: "user-photo", src: recipe.image, label: "User-confirmed photo", columns: 1, rows: 1, column: 0, row: 0, backgroundSize: "cover", backgroundPosition: "center" }
      : { status: "unreviewed-custom", kind: "unavailable", src: null, label: "Photo needs review", reason: "Confirm that your photo matches this recipe before displaying it." };
  }
  const matches = byName.get(recipeVisualNameKey(recipe?.name)) || [];
  const entry = matches.find((candidate) => candidate.ingredientSignature === recipeVisualIngredientSignature(recipe) &&
    (candidate.methodSignature === recipeVisualMethodSignature(recipe) ||
      reviewedMethods.get(recipeVisualNameKey(candidate.name)) === recipeVisualMethodSignature(recipe)));
  if (!entry) {
    return { status: matches.length ? "modified-recipe" : "unavailable", kind: "unavailable", src: null,
      label: "Recipe image needs review", reason: "No reviewed image matches these ingredients." };
  }
  return { ...entry, status: "reviewed", kind: "illustration", label: RECIPE_VISUAL_REVIEW.label,
    note: RECIPE_VISUAL_REVIEW.note,
    backgroundSize: `${entry.columns * 100}% ${entry.rows * 100}%`,
    backgroundPosition: `${entry.column / (entry.columns - 1) * 100}% ${entry.row / (entry.rows - 1) * 100}%`,
    sourceRect: { x: entry.column * entry.width / entry.columns, y: entry.row * entry.height / entry.rows,
      width: entry.width / entry.columns, height: entry.height / entry.rows }
  };
}
